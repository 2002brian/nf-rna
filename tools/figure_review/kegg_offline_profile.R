# OFFLINE TEST FIXTURE for the KEGG backend (review and regression tests only; never used in production).
#
# Loaded through R_PROFILE_USER.  It replaces the three network touch points of kegg_analysis.R -- the
# resource probe (url()), enrichKEGG() and gseKEGG() -- so the real backend script, config handling,
# mapping, tables, dotplots and manifests run without KEGG access:
#   * the probe reads fixtures/kegg_list_pathway_mmu.txt, a file in the format of the KEGG REST
#     "list/pathway/mmu" response (real pathway names);
#   * enrichKEGG()/gseKEGG() return deterministic SYNTHETIC statistics over those pathway names.
#     They are NOT scientific results.  Every output directory receives SYNTHETIC_KEGG_FIXTURE.txt.
# Scenario (NF_RNA_KEGG_SCENARIO): many | few | long | short | nonsig | empty.
local({
  dir <- Sys.getenv("NF_RNA_KEGG_FIXTURE_DIR"); scenario <- Sys.getenv("NF_RNA_KEGG_SCENARIO", "many")
  if (!nzchar(dir)) stop("NF_RNA_KEGG_FIXTURE_DIR is not set")
  lines <- readLines(file.path(dir, "kegg_list_pathway_mmu.txt"), warn = FALSE)
  parts <- strsplit(lines, "\t", fixed = TRUE)
  pathways <- data.frame(ID = sub("^path:", "", vapply(parts, `[`, "", 1)), Description = sub(" - Mus musculus \\(house mouse\\)$", "", vapply(parts, `[`, "", 2)), stringsAsFactors = FALSE)
  pathways <- pathways[order(pathways$ID), , drop = FALSE]
  pick <- function() {
    chosen <- switch(scenario,
      many = pathways[seq_len(min(24, nrow(pathways))), ],
      few = pathways[c(4, 10, 21), ],
      long = pathways[nchar(pathways$Description) >= 28, ][1:12, ],
      short = pathways[nchar(pathways$Description) <= 14, ],
      nonsig = pathways[seq(2, 20, by = 3), ],
      empty = pathways[0, ],
      stop("unknown NF_RNA_KEGG_SCENARIO: ", scenario))
    chosen[!is.na(chosen$ID), , drop = FALSE]
  }
  notice <- function() {
    out <- tryCatch(get("cfg", envir = globalenv())$output_dir, error = function(e) NULL)
    if (!is.null(out)) writeLines(c("SYNTHETIC KEGG FIXTURE", "The statistics in this directory were generated by tools/figure_review/kegg_offline_profile.R", "for figure review and regression tests. They are not scientific results."), file.path(out, "SYNTHETIC_KEGG_FIXTURE.txt"))
  }
  assign("url", function(description, open = "", ...) {
    if (grepl("^https://rest\\.kegg\\.jp/list/pathway/", description)) base::url(paste0("file://", file.path(dir, "kegg_list_pathway_mmu.txt")), open = open, ...) else base::url(description, open, ...)
  }, envir = globalenv())
  assign("enrichKEGG", function(gene, organism, keyType, universe, pvalueCutoff, pAdjustMethod, qvalueCutoff, minGSSize, maxGSSize, use_internal_data) {
    notice(); terms <- pick(); if (!nrow(terms)) return(NULL)
    n <- nrow(terms); i <- seq_len(n); gene <- as.character(gene)
    p <- if (scenario == "nonsig") 0.2 + 0.07 * i else 10^(-(2 + 1.3 * i))
    count <- pmin(length(gene), pmax(2L, as.integer(round(14 - 0.45 * i + (i * 7) %% 5))))
    adjusted <- pmin(1, p * n)
    data.frame(ID = terms$ID, Description = terms$Description, GeneRatio = sprintf("%d/%d", count, length(gene)), BgRatio = sprintf("%d/%d", count * 9L + 11L, length(universe)),
      pvalue = p, p.adjust = adjusted, qvalue = adjusted, geneID = vapply(count, function(k) paste(rep_len(gene, k), collapse = "/"), ""), Count = count, stringsAsFactors = FALSE)
  }, envir = globalenv())
  assign("gseKEGG", function(geneList, organism, keyType, pvalueCutoff, pAdjustMethod, minGSSize, maxGSSize, eps, verbose, seed) {
    notice(); terms <- pick(); if (!nrow(terms)) return(NULL)
    n <- nrow(terms); i <- seq_len(n); ids <- names(geneList)
    nes <- ifelse(i %% 3 == 0, -1, 1) * (2.6 - 0.07 * i - 0.2 * (i %% 4))
    p <- if (scenario == "nonsig") 0.2 + 0.07 * i else 10^(-(2.5 + 0.9 * i))
    size <- pmin(length(ids), as.integer(30 + (i * 37) %% 140))
    data.frame(ID = terms$ID, Description = terms$Description, setSize = size, enrichmentScore = nes / 3.1, NES = nes, pvalue = p, p.adjust = pmin(1, p * n), qvalue = pmin(1, p * n),
      rank = as.integer(10 + i * 40), leading_edge = sprintf("tags=%d%%, list=%d%%, signal=%d%%", 30L + i %% 20, 10L + i %% 15, 25L + i %% 25),
      core_enrichment = vapply(seq_len(n), function(k) paste(ids[seq_len(min(8L + k %% 5, length(ids)))], collapse = "/"), ""), stringsAsFactors = FALSE)
  }, envir = globalenv())
})
